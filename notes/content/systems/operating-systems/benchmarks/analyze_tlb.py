"""Summarize tlb_sweep and tlb_stride results: median, min and max per point.

Usage: python3 analyze_tlb.py tlb_sweep-results.jsonl tlb_stride-results.jsonl > tlb-summary.json
Optionally writes the figure's data module with --ts PATH.
"""
import json
import statistics
import sys
from collections import defaultdict


def load(path):
    with open(path) as f:
        return [json.loads(line) for line in f if line.strip()]


def summarize(rows, key, value):
    groups = defaultdict(list)
    for r in rows:
        groups[(r["pages"], r[key])].append(r[value])
    out = []
    for (page, k), v in sorted(groups.items(), key=lambda kv: (kv[0][1], kv[0][0])):
        out.append({"page": page, key: k, "n": len(v), "median": round(statistics.median(v), 2),
                    "min": round(min(v), 2), "max": round(max(v), 2)})
    return out


def main():
    args = sys.argv[1:]
    ts = None
    if "--ts" in args:
        i = args.index("--ts")
        ts = args[i + 1]
        del args[i:i + 2]
    sweep, stride = load(args[0]), load(args[1])
    # Every huge-page run must actually have been backed by huge pages.
    for r in sweep:
        if r["pages"] != "4K":
            need = r["region_bytes"] // 1024
            assert r["huge_kb"] >= min(need, 2 ** 20) * (0.99 if r["pages"] == "2M" else 1), r
        else:
            assert r["huge_kb"] == 0, r
    summary = {
        "sweep": summarize(sweep, "region_bytes", "ns_per_load"),
        "stride": summarize(stride, "stride", "ns_per_access"),
    }
    json.dump(summary, sys.stdout, indent=1)
    if ts:
        with open(ts, "w") as f:
            f.write("// Generated by analyze_tlb.py from tlb_sweep-results.jsonl beside the TLB note:\n")
            f.write("// median, min and max ns per load over the runs, per page size and region size.\n\n")
            f.write("export interface Point { page: \"4K\" | \"2M\" | \"1G\"; bytes: number; median: number; min: number; max: number; }\n\n")
            f.write("export const MEASURED: Point[] = [\n")
            for p in summary["sweep"]:
                f.write(f"  {{ page: \"{p['page']}\", bytes: {p['region_bytes']}, median: {p['median']}, min: {p['min']}, max: {p['max']} }},\n")
            f.write("];\n")


if __name__ == "__main__":
    main()
