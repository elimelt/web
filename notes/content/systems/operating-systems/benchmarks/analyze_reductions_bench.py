#!/usr/bin/env python3
"""Summarize the reductions benchmark.

Reads reductions_bench-*.jsonl beside this script and writes
reductions_bench-summary.json and the figure's data module
(quartz-site/plugins/mdx/src/components/reduction-sweep/measured.ts).

Every statistic is a median: first over the samples of one cell in one run,
then over runs. Spread is the min and max of the per-run medians.
"""
import json
import statistics as st
from pathlib import Path

HERE = Path(__file__).resolve().parent
FIG = HERE.parents[3] / "quartz-site/plugins/mdx/src/components/reduction-sweep/measured.ts"

VARIANTS = ["naive_scalar", "ilp_scalar", "naive", "ilp", "simd", "ilp_simd", "ilp_avx512", "opt",
            "thread_spawn", "thread_pool", "all_spawn", "all_pool"]
LINES = ["scalar_8_per_line", "scalar_4_per_line", "scalar_2_per_line", "scalar_1_per_line",
         "ymm_2_per_line", "zmm_1_per_line", "zmm4_1_per_line"]
# Regions by array size on the test VM (L1d 48 KiB, L2 2 MiB, L3 260 MiB).
REGIONS = {"L1": (16 << 10, 32 << 10), "L2": (64 << 10, 1 << 20), "L3": (8 << 20, 64 << 20), "DRAM": (512 << 20, 4 << 30)}


def jsonl(name):
    return [json.loads(l) for l in (HERE / name).read_text().splitlines() if l.strip()]


def spread(xs):
    return {"median": round(st.median(xs), 4), "min": round(min(xs), 4), "max": round(max(xs), 4), "n": len(xs)}


def main():
    clock = [r["clock_ghz"] for r in jsonl("reductions_bench-clock.jsonl")]
    ghz = st.median(clock)

    sweep = jsonl("reductions_bench-sweep.jsonl")
    assert all(r["ok"] for r in sweep), "a variant returned the wrong sum"
    per = {}
    for r in sweep:
        per.setdefault((r["variant"], r["bytes"]), []).append(st.median(r["ns_per_call"]) / (r["bytes"] / 8))
    sizes = sorted({b for _, b in per})
    cells = {}
    for v in VARIANTS:
        cells[v] = []
        for b in sizes:
            s = spread(per[(v, b)])
            cells[v].append({"bytes": b, "ns_per_elem": s["median"], "min": s["min"], "max": s["max"],
                             "gbs": round(8 / s["median"], 3), "elems_per_cycle": round(1 / (s["median"] * ghz), 3)})

    regions = {}
    for name, (lo, hi) in REGIONS.items():
        regions[name] = {v: round(st.median([c["gbs"] for c in cells[v] if lo <= c["bytes"] <= hi]), 2) for v in VARIANTS}

    disp = {}
    for r in jsonl("reductions_bench-dispatch.jsonl"):
        disp.setdefault(r["dispatch"], []).extend(r["ns_per_call"])
    dispatch = {}
    for k, xs in disp.items():
        xs = sorted(xs)
        dispatch[k] = {"median_us": round(st.median(xs) / 1000, 3), "p10_us": round(xs[len(xs) // 10] / 1000, 3),
                       "p90_us": round(xs[9 * len(xs) // 10] / 1000, 3), "n": len(xs)}

    scale = {}
    for r in jsonl("reductions_bench-scale.jsonl"):
        scale.setdefault(f'{r["variant"]}/{r["threads"]}', []).append(r["bytes"] / st.median(r["ns_per_call"]))
    scale = {k: spread(v) for k, v in sorted(scale.items())}

    lat = [st.median(r["ns_per_load"]) for r in jsonl("reductions_bench-latency.jsonl")]
    latency = spread(lat)

    lines = {}
    for r in jsonl("reductions_bench-lines.jsonl"):
        lines.setdefault(r["variant"], []).append(r["bytes"] / st.median(r["ns_per_call"]))
    lines_out = {}
    for v in LINES:
        s = spread(lines[v])
        # Little's law: lines in flight = (lines per ns) * (ns per line fetch).
        s["lines_in_flight"] = round(s["median"] / 64 * latency["median"], 1)
        lines_out[v] = s

    # Smallest size at which a threaded variant is faster than the fastest
    # single-thread variant at that size.
    single = VARIANTS[:8]
    crossover = {}
    for v in ["thread_spawn", "thread_pool", "all_spawn", "all_pool"]:
        crossover[v] = next((b for i, b in enumerate(sizes)
                             if cells[v][i]["ns_per_elem"] < min(cells[s][i]["ns_per_elem"] for s in single)), None)

    summary = {"clock_ghz": spread(clock), "sizes": sizes, "cells": cells, "regions_gbs": regions,
               "dispatch": dispatch, "scale_gbs": scale, "latency_ns": latency, "lines_gbs": lines_out,
               "crossover_bytes": crossover}
    (HERE / "reductions_bench-summary.json").write_text(json.dumps(summary, indent=1) + "\n")

    ts = ["// Generated by content/systems/operating-systems/benchmarks/analyze_reductions_bench.py",
          "// from the reductions benchmark runs. Do not edit by hand.", "",
          f"export const CLOCK_GHZ = {round(ghz, 4)};",
          f"export const SIZES: readonly number[] = {json.dumps(sizes)};",
          "/** Median ns per element, then min and max of the per-run medians, one entry per size. */",
          "export const NS_PER_ELEM: Record<string, readonly (readonly [number, number, number])[]> = {"]
    for v in VARIANTS:
        ts.append(f'  {v}: {json.dumps([[c["ns_per_elem"], c["min"], c["max"]] for c in cells[v]])},')
    ts += ["};", "/** Median cost in microseconds of a parallel call with no work. */",
           "export const DISPATCH_US = {"
           f' spawn: {dispatch["spawn"]["median_us"]}, poolHot: {dispatch["pool_hot"]["median_us"]},'
           f' poolCold: {dispatch["pool_cold"]["median_us"]} }};', ""]
    FIG.parent.mkdir(parents=True, exist_ok=True)
    FIG.write_text("\n".join(ts))
    print(json.dumps({"clock_ghz": summary["clock_ghz"], "regions_gbs": regions, "dispatch": dispatch,
                      "latency": latency, "lines": lines_out, "crossover": crossover, "scale": scale}, indent=1))


if __name__ == "__main__":
    main()
