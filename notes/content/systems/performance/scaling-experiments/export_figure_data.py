#!/usr/bin/env python3
"""Writes the scaling-fit figure's data module from raw.jsonl and the two published datasets."""
import json, sys
raw = [json.loads(l) for l in open(sys.argv[1])]
def runs(w):
    if w == "xz":  # N = 1 from -T+1 (same encoder as N >= 2)
        sel = [r for r in raw if (r["workload"] == "xz" and r["n"] > 1) or r["workload"] == "xz_mt1"]
    else:
        sel = [r for r in raw if r["workload"] == w]
    rs = sorted(sel, key=lambda r: (r["n"], r["rep"]))
    return [r["n"] for r in rs], [1 / r["seconds"] for r in rs]
sets = []
for key, w, label, xl, src in [
    ("kernel", "amdahl", "5% serial kernel", "threads", "A 50-unit serial phase followed by 950 units split over N pinned threads (designed serial fraction 0.05), 7 runs per N, on a 4-vCPU KVM guest (Intel Xeon, family 6 model 207). Throughput is runs per second."),
    ("xz", "xz", "xz -3 on Silesia", "threads", "xz 5.4.5, xz -T N -3 on the 212 MB Silesia corpus (N = 1 is -T+1, the same block encoder with one thread), 5 runs per N, same machine."),
    ("counter", "counter", "shared atomic counter", "threads", "N pinned threads perform 120 million relaxed atomic increments of one shared counter in total, 7 runs per N, same machine."),
]:
    n, x = runs(w)
    sets.append(dict(key=key, label=label, unit="runs/s", xLabel=xl, source=src, n=n, x=x, extrapolate=32))
sets.append(dict(key="specsdm91", label="SPEC SDM91 (16-CPU Sun)", unit="scripts/h", xLabel="simulated users", extrapolate=240,
    source="SPEC SDM91 results for a 16-CPU Sun SPARCcenter 2000 (October 1994), as distributed in the R usl package after Gunther (2007). One value per load level.",
    n=[1, 18, 36, 72, 108, 144, 216], x=[64.9, 995.9, 1652.4, 1853.2, 1828.9, 1775.0, 1702.2]))
sets.append(dict(key="raytracer", label="ray tracer (64-CPU SGI)", unit="intersections/s", xLabel="processors", extrapolate=96,
    source="BRL-CAD ray tracer on an SGI Origin 2000 with 64 R12000 processors, as distributed in the R usl package after Gunther (2007). The values are rounded in the source.",
    n=[1, 4, 8, 12, 16, 20, 24, 28, 32, 48, 64], x=[20, 78, 130, 170, 190, 200, 210, 230, 260, 280, 310]))
with open(sys.argv[2], "w") as f:
    f.write("// Generated by content/systems/performance/scaling-experiments/export_figure_data.py from\n")
    f.write("// raw.jsonl and the two published datasets. Do not edit by hand.\n\n")
    f.write('import type { Dataset } from "./model";\n\n')
    f.write('export const DEFAULT_KEY = "kernel";\n\n')
    f.write("export const DATASETS: Dataset[] = " + json.dumps(sets, indent=2) + ";\n")
