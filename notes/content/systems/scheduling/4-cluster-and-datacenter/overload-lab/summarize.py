#!/usr/bin/env python3
"""Summarizes results.jsonl: prints a table per policy and writes the
compact data module the overload-lab figure replays
(notes/quartz-site/plugins/mdx/src/components/overload-lab/measured.ts)."""
import json, os, statistics, sys
from collections import defaultdict

HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(HERE, "../../../../../quartz-site/plugins/mdx/src/components/overload-lab/measured.ts")
FIGURE_POLICIES = ["none", "fixed", "queue", "codel", "gradient"]

rows = [json.loads(l) for l in open(os.path.join(HERE, "results.jsonl"))]
by = defaultdict(list)
for r in rows:
    by[(r["policy"], r["rate"])].append(r)
rates = sorted({r["rate"] for r in rows})
policies = [p for p in ["none", "fixed", "queue", "codel", "gradient", "gradient-v1"] if any(k[0] == p for k in by)]

print(f"{'policy':12s} {'rate':>5s} {'n':>2s} {'goodput (min-max)':>22s} {'shed':>7s} {'timeout':>7s} {'p99 ms':>7s} {'done/s':>7s} {'useful':>6s}")
for p in policies:
    for rate in rates:
        rs = by.get((p, rate), [])
        if not rs:
            continue
        g = [r["goodput_rps"] for r in rs]
        p99 = [r["p99_ms"] for r in rs if r["p99_ms"] >= 0]
        done = [r["server_completions"] / r["elapsed_s"] for r in rs]
        useful = statistics.median(g) / statistics.median(done) if statistics.median(done) else 0
        print(f"{p:12s} {rate:5d} {len(rs):2d} {statistics.median(g):8.0f} ({min(g):5.0f}-{max(g):5.0f}) "
              f"{statistics.median(r['shed_rps'] for r in rs):7.0f} {statistics.median(r['timeout_rps'] for r in rs):7.0f} "
              f"{(statistics.median(p99) if p99 else -1):7.1f} {statistics.median(done):7.0f} {useful:6.2f}")

data = {"rates": rates, "policies": {}}
for p in FIGURE_POLICIES:
    data["policies"][p] = {}
    for rate in rates:
        rs = sorted(by.get((p, rate), []), key=lambda r: r["seed"])
        if not rs:
            continue
        data["policies"][p][str(rate)] = {
            "goodput": [round(r["goodput_rps"], 1) for r in rs],
            "shed": [round(r["shed_rps"], 1) for r in rs],
            "timeout": [round(r["timeout_rps"], 1) for r in rs],
            "p99": [round(r["p99_ms"], 1) for r in rs],
            "series": [r["goodput_per_second"] for r in rs],
        }
# The spike runs: base 1400/s, 3500/s from 4 s to 6 s, 16 s, with 2 immediate
# retries (spike.jsonl) and, for the server without admission control, none
# (spike-noretry.jsonl).
spike = {}
for name, retries in (("spike.jsonl", 2), ("spike-noretry.jsonl", 0)):
    path = os.path.join(HERE, name)
    if not os.path.exists(path):
        continue
    for r in map(json.loads, open(path)):
        d = spike.setdefault(str(retries), {}).setdefault(r["policy"], {"goodput": [], "attempts": []})
        d["goodput"].append(r["goodput_per_second"])
        d["attempts"].append(r["attempts_per_second"])
for retries, pols in spike.items():
    for p, d in pols.items():
        g = [statistics.median(x) for x in zip(*d["goodput"])]
        a = [statistics.median(x) for x in zip(*d["attempts"])]
        print(f"spike retries={retries} {p:9s} goodput/s {[int(v) for v in g]}")
        print(f"{'':27s} attempts/s {[int(v) for v in a]}")

if "--write" in sys.argv:
    with open(OUT, "w") as f:
        f.write("// Generated by content/systems/scheduling/4-cluster-and-datacenter/overload-lab/summarize.py\n")
        f.write("// from results.jsonl: the real Go server under open-loop Poisson load, 3 seeds per point.\n")
        f.write("// goodput, shed and timeout are callers per second over seconds 2-12; p99 is in ms (-1: none succeeded);\n")
        f.write("// series is goodput per second over the whole 12 s run, by arrival second.\n\n")
        f.write("export interface MeasuredPoint { goodput: number[]; shed: number[]; timeout: number[]; p99: number[]; series: number[][] }\n")
        f.write("export const MEASURED: { rates: number[]; policies: Record<string, Record<string, MeasuredPoint>> } = ")
        f.write(json.dumps(data, separators=(",", ":")) + ";\n\n")
        f.write("// The spike runs, keyed by retries then policy: per-second goodput and attempts, one array per seed.\n")
        f.write("export const SPIKE: Record<string, Record<string, { goodput: number[][]; attempts: number[][] }>> = ")
        f.write(json.dumps(spike, separators=(",", ":")) + ";\n")
    print("wrote", os.path.normpath(OUT), os.path.getsize(OUT), "bytes")
