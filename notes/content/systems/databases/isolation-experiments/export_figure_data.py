"""Writes the schedule checker's MySQL recordings from anomalies.json.

  python3 export_figure_data.py ../../../../quartz-site/plugins/mdx/src/components/schedule-checker/mysql.ts
"""
import json, sys

d = json.load(open("anomalies.json"))
out = {}
for name, by_db in d["runs"].items():
    if name.startswith("P3"):
        continue  # inserts and predicates; the figure's schedules are item reads and writes
    out[name] = {}
    for level, run in by_db["mysql"].items():
        steps = []
        for s in run["steps"]:
            op = s["step"][0]
            if s["status"] == "skipped":
                steps.append({"kind": "skipped"}); continue
            extra = {"releasedAt": s["released_after_step"]} if s.get("waited") else {}
            if s["status"] == "error":
                steps.append({"kind": "error", "code": s["error"], "message": s["message"], **extra}); continue
            v = s.get("value")
            if op == "w":
                v = s["step"][3]
            elif op == "add":
                op = "w"
            entry = {"kind": "ok", **extra}
            if op in ("r", "w"):
                entry["value"] = v
            steps.append(entry)
        commits = [s for s in run["steps"] if s["step"][0] == "c"]
        committed = sorted(s["step"][1] for s in commits if s["status"] == "ok")
        out[name][level] = {"steps": steps, "final": run["final"], "committed": committed}

ts = f"""// Generated by content/systems/databases/isolation-experiments/export_figure_data.py
// from anomalies.json: what MySQL {d['versions']['mysql'].split('-')[0]} (InnoDB) did with each preset at each
// isolation level. Do not edit by hand.

import type {{ Outcome }} from "./model";

export const recorded: Record<string, Record<string, Outcome>> = {json.dumps(out, separators=(',', ':'))};
"""
open(sys.argv[1], "w").write(ts)
print(len(ts), "bytes")
