#!/usr/bin/env python3
"""Summarize sem-results.json: a text table with the closed-form prediction
beside each measurement, and the data file the RetryLab figure loads.

Usage: python3 summarize_sem.py [sem-results.json]
"""
import itertools
import json
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
FIG_DATA = os.path.join(HERE, "../../../../quartz-site/plugins/mdx/src/components/retry-lab/data.ts")
BINS = 5


def model(q, r, sends, mode):
    """Brute-force enumeration over the 3^sends outcome sequences (independent
    of the figure's dynamic program): returns P(executions = k, ok) binned."""
    probs = {"lost": q, "orphan": (1 - q) * r, "success": (1 - q) * (1 - r)}
    ok = [0.0] * BINS
    fail = [0.0] * BINS
    seen = set()
    for seq in itertools.product(probs, repeat=sends):
        # truncate at the first success; skip sequences that duplicate a prefix
        if "success" in seq:
            seq = seq[: seq.index("success") + 1]
        if seq in seen:
            continue
        seen.add(seq)
        p = 1.0
        for o in seq:
            p *= probs[o]
        k = sum(o != "lost" for o in seq)
        if mode == "amo":
            k = min(k, 1)
        (ok if seq[-1] == "success" else fail)[min(k, BINS - 1)] += p
    return ok, fail


def frac_stats(values):
    return [sum(values) / len(values), min(values), max(values)]


def main():
    path = sys.argv[1] if len(sys.argv) > 1 else os.path.join(HERE, "sem-results.json")
    data = json.load(open(path))
    res = data["results"]
    loss = [x for x in res if not x["crash_ms"]]
    crash = [x for x in res if x["crash_ms"]]
    groups = {}
    for x in loss:
        groups.setdefault((x["mode"], x["q"], x["r"]), []).append(x)
    measured = []
    lines = [
        "Executions per call, at-least-once (alo) vs at-most-once (amo), 4 sends, 20 ms timeout.",
        "Kernel drops via iptables statistic match on lo. Model = exact enumeration.",
        f"Machine: {data['machine']}",
        "",
        f"{'mode':4} {'q':>5} {'r':>5} | {'ok meas':>8} {'ok mod':>7} | {'dup meas':>9} {'dup mod':>8} | {'err+exec meas':>13} {'mod':>6} | {'req drop':>8} {'rep drop':>8} | runs x calls",
    ]
    for (mode, q, r), xs in sorted(groups.items()):
        def per_run(f):
            return frac_stats([f(x) for x in xs])
        n0 = xs[0]["calls"]
        hist = []
        for b in range(BINS):
            hist.append(per_run(lambda x, b=b: sum(v for k, v in x["hist"].items() if min(int(k), BINS - 1) == b) / x["calls"]))
        ok = per_run(lambda x: x["ok"])
        dup = per_run(lambda x: x["dup"])
        fail_exec = per_run(lambda x: sum(v for k, v in x["fail_hist"].items() if int(k) >= 1) / x["calls"])
        fail_none = per_run(lambda x: x["fail_hist"].get("0", 0) / x["calls"])
        req = sum(x["req_drop_rate"] for x in xs) / len(xs)
        rep = sum(x["rep_drop_rate"] for x in xs) / len(xs)
        mok, mfail = model(q, r, 4, mode)
        pok = sum(mok)
        pdup = sum(mok[2:]) + sum(mfail[2:])
        pfe = sum(mfail[1:])
        lines.append(
            f"{mode:4} {q:5.2f} {r:5.2f} | {ok[0]:8.4f} {pok:7.4f} | {dup[0]:9.4f} {pdup:8.4f} | {fail_exec[0]:13.4f} {pfe:6.4f} | {req:8.4f} {rep:8.4f} | {len(xs)} x {n0}"
        )
        r6 = lambda v: [round(t, 6) for t in v]
        measured.append({
            "mode": mode, "q": q, "r": r, "runs": len(xs), "calls": n0,
            "hist": [r6(h) for h in hist], "ok": r6(ok), "dup": r6(dup),
            "failExec": r6(fail_exec), "failNone": r6(fail_none),
            "reqDrop": round(req, 5), "repDrop": round(rep, 5),
        })
    lines += ["", "Crash runs: reply loss 0.1, SIGKILL every U(20,60) ms, unbounded retries.",
              f"{'mode':12} {'run':>3} {'calls':>6} {'crashes':>7} {'ok':>6} {'dup':>7} {'mean exec':>9}"]
    for x in crash:
        lines.append(f"{x['mode']:12} {x['run']:3d} {x['calls']:6d} {x['crashes']:7d} {x['ok']:6.3f} {x['dup']:7.4f} {x['mean_exec']:9.4f}")
    txt = "\n".join(lines) + "\n"
    open(os.path.join(HERE, "sem-results.txt"), "w").write(txt)
    print(txt)

    ts = [
        "// Generated by content/systems/distributed-systems/rpc-experiments/summarize_sem.py",
        "// from sem-results.json. Do not edit by hand.",
        "",
        "/** [mean, min, max] over runs. */",
        "export type Stat = [number, number, number];",
        "",
        "export interface Measured {",
        '  mode: "alo" | "amo";',
        "  q: number;",
        "  r: number;",
        "  runs: number;",
        "  calls: number;",
        "  /** Fraction of calls executed 0, 1, 2, 3 and 4+ times. */",
        "  hist: Stat[];",
        "  ok: Stat;",
        "  dup: Stat;",
        "  failExec: Stat;",
        "  failNone: Stat;",
        "  reqDrop: number;",
        "  repDrop: number;",
        "}",
        "",
        f"export const MEASURED: Measured[] = {json.dumps(measured)};",
        "",
    ]
    open(FIG_DATA, "w").write("\n".join(ts))


if __name__ == "__main__":
    main()
