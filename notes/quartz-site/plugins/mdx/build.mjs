// Bundles the plugin and its browser modules. Quartz loads local plugins
// without installing their dependencies, so dist/index.js carries everything
// it imports. Run `npm install && npm run build` here after changing src/.

import { createHash } from "node:crypto";
import { readdirSync } from "node:fs";
import { readFile } from "node:fs/promises";
import { builtinModules } from "node:module";
import path from "node:path";
import { fileURLToPath } from "node:url";
import * as esbuild from "esbuild";

const here = path.dirname(fileURLToPath(import.meta.url));
const componentsDir = path.join(here, "src/components");
const staticDir = path.join(here, "../../static/mdx");

const clients = readdirSync(componentsDir, { withFileTypes: true })
  .filter((entry) => entry.isDirectory())
  .map((entry) => entry.name);

const versions = {};
for (const name of clients) {
  const outfile = path.join(staticDir, `${name}.js`);
  await esbuild.build({
    entryPoints: [path.join(componentsDir, name, "client.ts")],
    outfile,
    bundle: true,
    format: "esm",
    platform: "browser",
    target: "es2020",
    minify: true,
    legalComments: "none",
  });
  versions[name] = createHash("sha256").update(await readFile(outfile)).digest("hex").slice(0, 10);
}

await esbuild.build({
  entryPoints: [path.join(here, "src/index.ts")],
  outfile: path.join(here, "dist/index.js"),
  bundle: true,
  format: "esm",
  platform: "node",
  target: "node22",
  external: [...builtinModules, ...builtinModules.map((m) => `node:${m}`)],
  define: { __MDX_MODULE_VERSIONS__: JSON.stringify(versions) },
  minify: true,
  legalComments: "none",
  banner: { js: "// Generated by build.mjs from src/. Do not edit." },
});

console.log(`Built dist/index.js and ${clients.length} browser module(s):`, versions);
