// Bundles the plugin and its browser modules. Quartz loads local plugins
// without installing their dependencies, so dist/index.js carries everything
// it imports. scripts/quartz.sh runs this before every site build and the
// outputs are not committed; run `npm install && npm run build` here to try a
// change without a full site build.
//
// Each directory under src/components/ is one component, found by name:
//   component.ts  `export const tag = "QueueLab";` (the name notes use) and
//                 `render(props)`, which returns the build-time markup;
//   client.ts     `mount(root)`, bundled to static/mdx/<directory>.js;
//   style.scss    optional, the figure's styles.
// Outputs:
//   dist/index.js          the Quartz plugin, with a generated registry;
//   ../../static/mdx/*.js  one browser module per component;
//   dist/components.scss   src/shared/figure.scss, then every style.scss in
//                          directory order; custom.scss loads it.

import { createHash } from "node:crypto";
import { existsSync, mkdirSync, readdirSync, readFileSync, writeFileSync } from "node:fs";
import { builtinModules } from "node:module";
import path from "node:path";
import { fileURLToPath } from "node:url";
import * as esbuild from "esbuild";

const here = path.dirname(fileURLToPath(import.meta.url));
const componentsDir = path.join(here, "src/components");
const staticDir = path.join(here, "../../static/mdx");

const TAG = /^export const tag = "([A-Z][A-Za-z0-9]*)";$/m;
const components = [];
for (const entry of readdirSync(componentsDir, { withFileTypes: true })) {
  if (!entry.isDirectory()) continue;
  const name = entry.name;
  const dir = path.join(componentsDir, name);
  for (const file of ["component.ts", "client.ts"]) {
    if (!existsSync(path.join(dir, file))) throw new Error(`src/components/${name}/ has no ${file}`);
  }
  const tag = TAG.exec(readFileSync(path.join(dir, "component.ts"), "utf8"))?.[1];
  if (!tag) throw new Error(`src/components/${name}/component.ts needs a line like: export const tag = "MyFigure";`);
  const clash = components.find((c) => c.tag === tag);
  if (clash) throw new Error(`<${tag}> is claimed by both ${clash.name} and ${name}`);
  components.push({ name, tag });
}
components.sort((a, b) => (a.name < b.name ? -1 : 1));

const versions = {};
for (const { name } of components) {
  const outfile = path.join(staticDir, `${name}.js`);
  await esbuild.build({
    entryPoints: [path.join(componentsDir, name, "client.ts")],
    outfile,
    bundle: true,
    format: "esm",
    platform: "browser",
    target: "es2020",
    minify: true,
    legalComments: "none",
  });
  versions[name] = createHash("sha256").update(readFileSync(outfile)).digest("hex").slice(0, 10);
}

// src/index.ts imports `components` from "mdx:components", which this plugin
// generates from the directories found above.
const registry = {
  name: "mdx-registry",
  setup(build) {
    build.onResolve({ filter: /^mdx:components$/ }, () => ({ path: "registry", namespace: "mdx" }));
    build.onLoad({ filter: /.*/, namespace: "mdx" }, () => ({
      resolveDir: componentsDir,
      loader: "ts",
      contents: [
        ...components.map(({ name }, i) => `import { render as r${i} } from "./${name}/component";`),
        "export const components = {",
        ...components.map(({ name, tag }, i) => `  ${tag}: { render: r${i}, module: ${JSON.stringify(name)} },`),
        "};",
      ].join("\n"),
    }));
  },
};

await esbuild.build({
  entryPoints: [path.join(here, "src/index.ts")],
  outfile: path.join(here, "dist/index.js"),
  bundle: true,
  format: "esm",
  platform: "node",
  target: "node22",
  external: [...builtinModules, ...builtinModules.map((m) => `node:${m}`)],
  define: { __MDX_MODULE_VERSIONS__: JSON.stringify(versions) },
  plugins: [registry],
  minify: true,
  legalComments: "none",
  banner: { js: "// Generated by build.mjs from src/. Do not edit." },
});

const styles = [["src/shared/figure.scss", path.join(here, "src/shared/figure.scss")]];
for (const { name } of components) {
  const file = path.join(componentsDir, name, "style.scss");
  if (existsSync(file)) styles.push([`src/components/${name}/style.scss`, file]);
}
mkdirSync(path.join(here, "dist"), { recursive: true });
writeFileSync(
  path.join(here, "dist/components.scss"),
  "// Generated by build.mjs from src/. Do not edit.\n" +
    styles.map(([label, file]) => `\n// ---- ${label}\n\n${readFileSync(file, "utf8")}`).join(""),
);

console.log(`Built dist/index.js, dist/components.scss and ${components.length} browser module(s):`, versions);
